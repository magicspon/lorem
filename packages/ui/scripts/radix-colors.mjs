#!/usr/bin/env node
// Writes `src/styles/radix.stylex.ts` from `@radix-ui/colors`. StyleX reads
// only literal values and `.stylex` imports, so the tokens can't import the
// package directly; this copies the scales they use into a file they can.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import * as colors from '@radix-ui/colors'

// The scales `tokens.stylex.ts` and `themes.ts` read. Add one here to use it.
const scales = [
  'sage',
  'mint',
  'red',
  'green',
  'amber',
  'blue',
  'violet',
  'orange',
  'crimson',
]
const variants = ['', 'A', 'Dark', 'DarkA']
// Alpha-only scales, the same in both schemes: `blackA` darkens a shadow on a
// dark page, where a neutral scale's dark alpha steps lighten.
const overlays = ['blackA']
// A map, so a scale is looked up by a name built at run time.
const radix = new Map(Object.entries(colors))

const target = fileURLToPath(
  new URL('../src/styles/radix.stylex.ts', import.meta.url),
)

const steps = (name, values) =>
  Object.entries(values)
    .map(([key, value]) => `  '${key.slice(name.length)}': '${value}',`)
    .join('\n')

const blocks = scales.flatMap((scale) =>
  variants.map((variant) => {
    const name = `${scale}${variant}`
    const values = radix.get(name)
    if (!values) throw new Error(`@radix-ui/colors has no ${name}`)
    // Radix keys a step as `sageA1`; the key here is the step alone.
    const prefix = variant.endsWith('A') ? `${scale}A` : scale
    return `export const ${name} = stylex.defineConsts({\n${steps(prefix, values)}\n})`
  }),
)
for (const name of overlays) {
  const values = radix.get(name)
  if (!values) throw new Error(`@radix-ui/colors has no ${name}`)
  blocks.push(
    `export const ${name} = stylex.defineConsts({\n${steps(name, values)}\n})`,
  )
}

writeFileSync(
  target,
  `// Generated by \`pnpm --filter @repo/ui colors\` from @radix-ui/colors. Do
// not edit; change the scales in \`scripts/radix-colors.mjs\` and run it again.
import * as stylex from '@stylexjs/stylex'

/** Radix Colors scales, keyed by step 1 to 12. See \`tokens.stylex.ts\`. */
${blocks.join('\n\n')}
`,
)
execFileSync('pnpm', ['exec', 'oxfmt', target], { stdio: 'inherit' })
